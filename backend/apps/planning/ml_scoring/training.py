"""Offline training pipeline for the LightGBM ranker.

Run as a Django management command or a standalone script. Pulls labels from
two sources:
    1. Real :class:`RecipeFeedback` rows when available.
    2. Synthetic labels generated by the deterministic scorer for cold start.

The output model file should be uploaded to S3 (path configured in ECS task
definition) so the worker container picks it up at startup.
"""
from __future__ import annotations

import json
import logging
import random
from collections import defaultdict
from dataclasses import dataclass
from pathlib import Path

import django

logger = logging.getLogger(__name__)


@dataclass(slots=True)
class TrainingConfig:
    output_path: Path
    train_synthetic: bool = True
    real_feedback_only: bool = False
    seed: int = 42
    num_boost_round: int = 200
    learning_rate: float = 0.05
    num_leaves: int = 31
    feature_fraction: float = 0.85
    min_data_in_leaf: int = 5


def _ensure_django() -> None:
    if not django.apps.apps.ready:
        import os

        os.environ.setdefault('DJANGO_SETTINGS_MODULE', 'config.settings.dev')
        django.setup()


def collect_dataset(config: TrainingConfig) -> tuple[list[list[float]], list[float], list[int], list[str]]:
    """Returns X, y, group_sizes, feature_names.

    - X is a flat list of feature vectors.
    - y is the relevance label per row.
    - group_sizes is the LightGBM-style group array (lengths sum to len(X)).
    - feature_names is shared with inference time.
    """
    _ensure_django()

    from apps.catalog.models import Recipe, RecipeStatus
    from apps.feedback.models import RecipeFeedback
    from apps.groups.models import Group
    from apps.planning.ml_scoring.features import RecipeGroupFeatureExtractor
    from apps.planning.services import _score_recipe_for_group

    extractor = RecipeGroupFeatureExtractor()
    rng = random.Random(config.seed)

    rows_by_group: dict[str, list[tuple[list[float], float]]] = defaultdict(list)

    real_pairs = list(
        RecipeFeedback.objects.select_related('group', 'recipe').all()
    )
    for feedback in real_pairs:
        if not feedback.group_id or not feedback.recipe_id:
            continue
        try:
            features = extractor.extract(feedback.recipe, feedback.group)
        except Exception:
            continue

        if feedback.rating is not None:
            label = float(feedback.rating) / 5.0
        elif feedback.liked is True:
            label = 1.0
        elif feedback.liked is False:
            label = 0.0
        else:
            continue
        rows_by_group[str(feedback.group_id)].append((features.values, label))

    if not config.real_feedback_only and config.train_synthetic:
        groups = Group.objects.prefetch_related('preferences', 'members__constraints').all()[:200]
        recipes = list(
            Recipe.objects.filter(status=RecipeStatus.PUBLISHED)
            .select_related('nutrition')
            .prefetch_related('recipe_tags__tag', 'ingredients_map__ingredient__prices')[:500]
        )
        for group in groups:
            sample_recipes = rng.sample(recipes, min(40, len(recipes)))
            for recipe in sample_recipes:
                features = extractor.extract(recipe, group)
                synthetic_score = _score_recipe_for_group(
                    recipe, group, optimization_focus=['budget', 'nutrition'],
                )
                rows_by_group[f'synth-{group.id}'].append(
                    (features.values, float(synthetic_score)),
                )

    X: list[list[float]] = []
    y: list[float] = []
    group_sizes: list[int] = []
    for group_key, rows in rows_by_group.items():
        if len(rows) < 2:
            continue
        for values, label in rows:
            X.append(values)
            y.append(label)
        group_sizes.append(len(rows))

    return X, y, group_sizes, extractor.feature_names


def train(config: TrainingConfig) -> Path:
    try:
        import lightgbm as lgb
    except ImportError as exc:
        raise RuntimeError(
            "lightgbm is required to train. Install with: pip install lightgbm"
        ) from exc
    import numpy as np

    X, y, group_sizes, feature_names = collect_dataset(config)
    if not X:
        raise RuntimeError('No training rows collected. Check feedback data and synthetic generation.')

    X_np = np.asarray(X, dtype=np.float32)
    y_np = np.asarray(y, dtype=np.float32)

    train_dataset = lgb.Dataset(X_np, label=y_np, group=group_sizes, feature_name=feature_names, free_raw_data=False)

    params = {
        'objective': 'lambdarank',
        'metric': ['ndcg'],
        'ndcg_at': [5, 10],
        'learning_rate': config.learning_rate,
        'num_leaves': config.num_leaves,
        'feature_fraction': config.feature_fraction,
        'min_data_in_leaf': config.min_data_in_leaf,
        'verbose': -1,
    }

    booster = lgb.train(params, train_dataset, num_boost_round=config.num_boost_round)

    config.output_path.parent.mkdir(parents=True, exist_ok=True)
    booster.save_model(str(config.output_path))

    metadata_path = config.output_path.with_suffix('.json')
    metadata_path.write_text(
        json.dumps(
            {
                'feature_names': feature_names,
                'num_rows': len(X),
                'num_groups': len(group_sizes),
                'params': params,
            },
            ensure_ascii=False,
            indent=2,
        ),
        encoding='utf-8',
    )

    logger.info(
        'ml_scoring: trained on %d rows (%d groups), saved to %s',
        len(X), len(group_sizes), config.output_path,
    )
    return config.output_path
