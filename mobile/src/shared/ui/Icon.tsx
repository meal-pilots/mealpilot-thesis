type IconProps = Omit<LucideProps, 'size'> & {
    name: IconName
    size?: number
}

export function Icon({ name, size = 20, color, strokeWidth = 2, ...rest }: IconProps) {
    const Component = icons[name]
    return <Component size={size} color={color} strokeWidth={strokeWidth} {...rest} />
}
